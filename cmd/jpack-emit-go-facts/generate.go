// Writing the Go source of a request's contracts (ADR-0100). Every text that
// comes from a contract (a pointer, a member name, a value, an id) reaches
// the source only through strconv.QuoteToASCII, so the files are ASCII, and
// no contract text can end a comment or a string literal.

// supportFile is the name of the file the contracts' files share.
const supportFile = "facts_support.go"

// header is the first line of every file: the emitter's id and version, and
// nothing else (RFC 0036 §4).
const header = "// Code generated by " + emitterID + " " + emitterVersion + ". DO NOT EDIT.\n"

// generate writes the response's files: one per contract and the support
// file, each formatted by go/format. A request with no contract writes no
// file.
func generate(contracts []*contract, opts options) ([]file, error) {
	if len(contracts) == 0 {
		return []file{}, nil
	}
	n := newNamer()
	for _, c := range contracts {
		if err := n.nameContract(c); err != nil {
			return nil, err
		}
	}
	files := make([]file, 0, len(contracts)+1)
	supportText := header + "\npackage " + opts.pkg + "\n" + supportSource
	total := len(supportText)
	support, err := formatted(supportText)
	if err != nil {
		return nil, err
	}
	files = append(files, file{path: opts.directory + "/" + supportFile, text: support})
	for _, c := range contracts {
		g := &writer{}
		g.contract(c, opts.pkg)
		// The bounds are held before go/format, whose cost grows with the
		// source: the source written here has no indentation or alignment,
		// so formatting never makes it shorter, and a source over a bound
		// would be over it formatted too. The response escapes every text,
		// which only lengthens it, so the sources' total is held to the
		// response bound. encodeResponse holds the formatted files to the
		// same bounds.
		total += g.b.Len()
		if g.b.Len() > maxFileBytes || total > maxResponseBytes {
			return nil, errBounds
		}
		text, err := formatted(g.b.String())
		if err != nil {
			return nil, err
		}
		files = append(files, file{path: opts.directory + "/" + c.stem + "_facts.go", text: text})
	}
	return files, nil
}

func formatted(source string) (string, error) {
	out, err := format.Source([]byte(source))
	if err != nil {
		return "", errInternal
	}
	return string(out), nil
}

// writer accumulates one file's source.
type writer struct {
	b strings.Builder
}

func (w *writer) line(parts ...string) {
	for _, p := range parts {
		w.b.WriteString(p)
	}
	w.b.WriteByte('\n')
}

func quote(s string) string { return strconv.QuoteToASCII(s) }

// contract writes one contract's file: the facts document's struct first,
// then every struct and enumeration below it, depth first, members in
// pointer order.
func (w *writer) contract(c *contract, pkg string) {
	w.line(header)
	w.line("package ", pkg)
	w.line()
	w.line("// ", c.root.typeName, " is a facts document under the facts contract")
	w.line("// ", quote(c.id), ", version ", quote(c.version), ".")
	if c.kind != nil {
		w.line("// The contract was generated from the kind ", quote(c.kind.id), ", version")
		w.line("// ", quote(c.kind.version), ", whose digest is ", quote(c.kind.digest), ".")
	} else {
		w.line("// The contract was written by hand.")
	}
	w.declare(c.root, true)
}

// declare writes the declarations of p and of every position below it.
func (w *writer) declare(p *position, root bool) {
	switch {
	case p.isStruct():
		w.structType(p, root)
		for _, m := range p.members {
			w.declare(m, false)
		}
	case p.isMap():
		w.declare(p.others, false)
	case p.typ == "array":
		w.declare(p.element, false)
	case p.isEnum():
		w.enumType(p)
	}
}

// goType is the Go type of a value at p, not counting optionality.
func goType(p *position) string {
	switch {
	case p.isEnum():
		return p.typeName
	case p.typ == "string":
		return "string"
	case p.typ == "decimal":
		return "Decimal"
	case p.typ == "boolean":
		return "bool"
	case p.typ == "null":
		return "struct{}"
	case p.typ == "array":
		return "[]" + goType(p.element)
	case p.isMap():
		return "map[string]" + goType(p.others)
	}
	return "*" + p.typeName
}

// fieldType is the Go type of the field for member m: a pointer when it is
// optional (nil leaves it out), except an optional null, which is a bool, and
// a struct, which is a pointer either way.
func fieldType(m *position) string {
	switch {
	case m.typ == "null":
		return "bool"
	case m.always || m.isStruct():
		return goType(m)
	}
	return "*" + goType(m)
}

func presence(m *position) string {
	switch {
	case m.typ == "null":
		return "optional: true writes null, false leaves it out"
	case !m.always:
		return "optional: nil leaves it out"
	case m.isStruct():
		return "always present: Build refuses nil"
	case m.typ == "array":
		return "always present: nil is written as []"
	case m.isMap():
		return "always present: nil is written as {}"
	}
	return "always present"
}

// required are the members of a struct that are constructor arguments: every
// member the contract always holds, except a null, which has no field.
func required(p *position) []*position {
	var out []*position
	for _, m := range p.members {
		if m.always && m.typ != "null" {
			out = append(out, m)
		}
	}
	return out
}

func (w *writer) structType(p *position, root bool) {
	if !root {
		w.line()
		w.line("// ", p.typeName, " is the object at ", quote(p.pointer), ".")
		if p.secret {
			w.line("// It stands for a secret reference: it holds the reference's store and")
			w.line("// scope, never the reference.")
		}
	}
	if len(p.members) == 0 {
		w.line("type ", p.typeName, " struct{}")
	} else {
		w.line("type ", p.typeName, " struct {")
		for _, m := range p.members {
			if m.always && m.typ == "null" {
				w.line("// ", quote(m.pointer), " is always null: Build writes it.")
				continue
			}
			w.line("// ", m.field, " is ", quote(m.pointer), ", ", presence(m), ".")
			w.line(m.field, " ", fieldType(m))
		}
		w.line("}")
	}

	args := required(p)
	w.line()
	w.line("// New", p.typeName, " returns a new ", p.typeName, " holding the members the contract")
	w.line("// always holds.")
	params := make([]string, len(args))
	keys := make([]string, len(args))
	for i, m := range args {
		params[i] = m.param + " " + fieldType(m)
		keys[i] = m.field + ": " + m.param
	}
	w.line("func New", p.typeName, "(", strings.Join(params, ", "), ") *", p.typeName, " {")
	w.line("return &", p.typeName, "{", strings.Join(keys, ", "), "}")
	w.line("}")

	if root {
		w.line()
		w.line("// Build returns the facts document as RFC 8785 canonical JSON. It returns a")
		w.line("// *BuildError, and no bytes, for a value the contract requires that is nil,")
		w.line("// a value outside the contract's values, or a string that is not valid UTF-8.")
		w.line("func (f *", p.typeName, ") Build() ([]byte, error) {")
		w.line("if f == nil {")
		w.line("return nil, missing(\"\")")
		w.line("}")
		w.line("return f.appendJSON(nil, \"\")")
		w.line("}")
	}

	w.line()
	w.line("func (f *", p.typeName, ") appendJSON(b []byte, at string) ([]byte, error) {")
	if len(p.members) == 0 {
		w.line("return append(b, '{', '}'), nil")
		w.line("}")
		return
	}
	if slices.ContainsFunc(p.members, needsErr) {
		w.line("var err error")
	}
	w.line("start := len(b) + 1")
	w.line("b = append(b, '{')")
	for _, m := range canonicalOrder(p.members) {
		w.member(m)
	}
	w.line("return append(b, '}'), nil")
	w.line("}")
}

// canonicalOrder is RFC 8785's order of an object's members: by the UTF-16
// code units of their names.
func canonicalOrder(members []*position) []*position {
	out := slices.Clone(members)
	slices.SortStableFunc(out, func(a, b *position) int {
		return slices.Compare(utf16.Encode([]rune(memberName(a))), utf16.Encode([]rune(memberName(b))))
	})
	return out
}

func memberName(m *position) string { return m.tokens[len(m.tokens)-1].name }

// needsErr says whether writing p calls a function that can refuse: a
// string, a struct's appendJSON, or a map's member names.
func needsErr(p *position) bool {
	switch {
	case p.typ == "string" || p.isStruct() || p.isMap():
		return true
	case p.typ == "array":
		return needsErr(p.element)
	}
	return false
}

// member writes one member of a struct's appendJSON.
func (w *writer) member(m *position) {
	name, err := jcs.Encode(memberName(m))
	if err != nil {
		// A member name decoded from the request is valid UTF-8, which is
		// all jcs.Encode asks of a string.
		panic("jpack-emit-go-facts: a member name has no canonical form")
	}
	nameLiteral := quote(string(name) + ":")
	at := "at+" + quote("/"+escapeToken(memberName(m)))
	field := "f." + m.field
	writeName := "b = appendName(b, start, " + nameLiteral + ")"
	switch {
	case m.typ == "null" && m.always:
		w.line(writeName)
		w.line("b = append(b, \"null\"...)")
	case m.typ == "null":
		w.line("if ", field, " {")
		w.line(writeName)
		w.line("b = append(b, \"null\"...)")
		w.line("}")
	case m.isStruct() && m.always:
		w.line("if ", field, " == nil {")
		w.line("return nil, missing(", at, ")")
		w.line("}")
		w.line(writeName)
		w.value(m, field, at, 0)
	case m.isStruct():
		w.line("if ", field, " != nil {")
		w.line(writeName)
		w.value(m, field, at, 0)
		w.line("}")
	case m.always:
		w.check(m, field, at)
		w.line(writeName)
		w.value(m, field, at, 0)
	default:
		w.line("if ", field, " != nil {")
		w.check(m, "*"+field, at)
		w.line(writeName)
		w.value(m, "*"+field, at, 0)
		w.line("}")
	}
}

// operand is expr ready for a selector or an index: a dereference is
// parenthesized.
func operand(expr string) string {
	if strings.HasPrefix(expr, "*") {
		return "(" + expr + ")"
	}
	return expr
}

// check writes the values check of a decimal or boolean: Build refuses any
// value outside the contract's list. A string enumeration is checked by its
// type's valid method, in value.
func (w *writer) check(p *position, expr, at string) {
	if !p.hasValues || p.typ == "string" {
		return
	}
	subject := expr
	cases := make([]string, len(p.values))
	for i, v := range p.values {
		cases[i] = v
		if p.typ == "decimal" {
			cases[i] = quote(v)
		}
	}
	if p.typ == "decimal" {
		subject = operand(expr) + ".String()"
	}
	w.line("switch ", subject, " {")
	w.line("case ", strings.Join(cases, ", "), ":")
	w.line("default:")
	w.line("return nil, notAllowed(", at, ")")
	w.line("}")
}

// value writes the JSON of the value expr, of position p, whose pointer is
// the expression at. depth numbers the loop variables of nested arrays and
// maps.
func (w *writer) value(p *position, expr, at string, depth int) {
	d := strconv.Itoa(depth)
	switch {
	case p.isEnum():
		w.line("if !", operand(expr), ".valid() {")
		w.line("return nil, notAllowed(", at, ")")
		w.line("}")
		w.line("if b, err = appendString(b, string(", expr, "), ", at, "); err != nil {")
		w.line("return nil, err")
		w.line("}")
	case p.typ == "string":
		w.line("if b, err = appendString(b, ", expr, ", ", at, "); err != nil {")
		w.line("return nil, err")
		w.line("}")
	case p.typ == "decimal":
		w.line("b = appendDecimal(b, ", expr, ")")
	case p.typ == "boolean":
		w.line("b = appendBool(b, ", expr, ")")
	case p.typ == "null":
		w.line("b = append(b, \"null\"...)")
	case p.typ == "array":
		i, e := "i"+d, "e"+d
		elementAt := "index(" + at + ", " + i + ")"
		w.line("b = append(b, '[')")
		if p.element.typ == "null" {
			w.line("for ", i, " := range ", expr, " {")
		} else {
			w.line("for ", i, ", ", e, " := range ", expr, " {")
		}
		w.line("if ", i, " > 0 {")
		w.line("b = append(b, ',')")
		w.line("}")
		w.item(p.element, e, elementAt, depth+1)
		w.line("}")
		w.line("b = append(b, ']')")
	case p.isMap():
		i, k := "i"+d, "k"+d
		memberAt := "member(" + at + ", " + k + ")"
		w.line("b = append(b, '{')")
		w.line("for ", i, ", ", k, " := range sortedNames(", expr, ") {")
		w.line("if ", i, " > 0 {")
		w.line("b = append(b, ',')")
		w.line("}")
		w.line("if b, err = appendString(b, ", k, ", ", memberAt, "); err != nil {")
		w.line("return nil, err")
		w.line("}")
		w.line("b = append(b, ':')")
		w.item(p.others, operand(expr)+"["+k+"]", memberAt, depth+1)
		w.line("}")
		w.line("b = append(b, '}')")
	default:
		w.line("if b, err = ", expr, ".appendJSON(b, ", at, "); err != nil {")
		w.line("return nil, err")
		w.line("}")
	}
}

// item writes an array element or a map member's value: a struct is refused
// when nil, and every value is checked against its list.
func (w *writer) item(p *position, expr, at string, depth int) {
	if p.isStruct() {
		w.line("if ", expr, " == nil {")
		w.line("return nil, missing(", at, ")")
		w.line("}")
	}
	w.check(p, expr, at)
	w.value(p, expr, at, depth)
}

// escapeToken writes a member name as an RFC 6901 token, for the pointers
// Build reports.
func escapeToken(name string) string {
	return strings.ReplaceAll(strings.ReplaceAll(name, "~", "~0"), "/", "~1")
}

func (w *writer) enumType(p *position) {
	w.line()
	w.line("// ", p.typeName, " is a string at ", quote(p.pointer), ": one of the contract's")
	w.line("// values, which Build checks.")
	w.line("type ", p.typeName, " string")
	w.line()
	w.line("// The values of ", p.typeName, ".")
	w.line("const (")
	names := make([]string, len(p.values))
	for i, v := range p.values {
		names[i] = p.typeName + part(v)
		w.line(names[i], " ", p.typeName, " = ", quote(v))
	}
	w.line(")")
	w.line()
	w.line("// valid says whether v is one of the contract's values.")
	w.line("func (v ", p.typeName, ") valid() bool {")
	w.line("switch v {")
	w.line("case ", strings.Join(names, ", "), ":")
	w.line("return true")
	w.line("}")
	w.line("return false")
	w.line("}")
}
