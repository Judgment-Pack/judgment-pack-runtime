package main

import (
	"go/format"
	"strconv"
	"strings"
)

// Writing the Go source of a request's kinds (ADR-0102). The only names the
// source holds outside a string literal are the emitter's own and those the
// naming rule forms, each held to identifier. Every text that comes from a
// declaration (a kind name, an id, a version, a digest, a member name, a
// value or a pointer) reaches the source only through strconv.QuoteToASCII,
// so the files are ASCII, and no declaration text can end a comment or a
// string literal. A schema's descriptions are never copied.

// loaderFile is the name of the file the kind files share.
const loaderFile = "loader.go"

// header is the first line of every file: the emitter's id and version, and
// nothing else (RFC 0036 §4). A resolved document's registry digest is not in
// it, so an edit to an entry does not change the files.
const header = "// Code generated by " + emitterID + " " + emitterVersion + ". DO NOT EDIT.\n"

// generate builds, names and writes the request's kinds: loader.go and one
// file per kind, each formatted by go/format. A request with no kind writes
// no file. A declaration it cannot generate code for is a *findingAt at its
// kind.
func generate(kinds []*kind, opts options) ([]file, error) {
	if len(kinds) == 0 {
		return []file{}, nil
	}
	n := newNamer()
	total := 0
	for _, k := range kinds {
		root, count, err := buildKind(k)
		if err != nil {
			return nil, locate(err, k)
		}
		if total += count; total > maxRequestPositions {
			return nil, errBounds
		}
		k.root = root
		if err := n.nameKind(k); err != nil {
			return nil, locate(err, k)
		}
	}
	files := make([]file, 0, len(kinds)+1)
	loader, err := formatted(loaderSource(kinds, opts.pkg))
	if err != nil {
		return nil, err
	}
	files = append(files, file{path: opts.directory + "/" + loaderFile, text: loader})
	for _, k := range kinds {
		w := &writer{}
		w.kindFile(k, opts.pkg)
		text, err := formatted(w.b.String())
		if err != nil {
			return nil, err
		}
		files = append(files, file{path: opts.directory + "/" + k.stem + "_kind.go", text: text})
	}
	return files, nil
}

// locate places a finding at its kind.
func locate(err error, k *kind) error {
	if f, ok := err.(finding); ok {
		return &findingAt{code: f, kind: k.name}
	}
	return err
}

func formatted(source string) (string, error) {
	out, err := format.Source([]byte(source))
	if err != nil {
		return "", errInternal
	}
	return string(out), nil
}

func quote(s string) string { return strconv.QuoteToASCII(s) }

// loaderSource is loader.go: the shared source, and the table of the kinds
// Load checks.
func loaderSource(kinds []*kind, pkg string) string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\npackage " + pkg + "\n")
	b.WriteString(supportSource)
	b.WriteString("\n// readKinds are the kinds this package was generated for, in the order of\n")
	b.WriteString("// their names.\n")
	b.WriteString("var readKinds = []readKind{\n")
	for _, k := range kinds {
		b.WriteString("{name: " + quote(k.name) + ", id: " + quote(k.id) + ", version: " + quote(k.version) + ",\n")
		b.WriteString("check: func(d *decoder, raw json.RawMessage) error {\n")
		b.WriteString("_, err := decode" + k.typeName + "(d, \"\", raw)\n")
		b.WriteString("return err\n")
		b.WriteString("}},\n")
	}
	b.WriteString("}\n")
	return b.String()
}

// writer accumulates one file's source.
type writer struct {
	b strings.Builder
}

func (w *writer) line(parts ...string) {
	for _, p := range parts {
		w.b.WriteString(p)
	}
	w.b.WriteByte('\n')
}

// kindFile writes one kind's file: its type and every type below it, depth
// first and members in name order, then its Registry methods, then the
// decoders of its structs and enumerations.
func (w *writer) kindFile(k *kind, pkg string) {
	secrets := hasSecret(k.root)
	w.line(header)
	w.line("package ", pkg)
	w.line()
	w.line("import (")
	w.line(quote("context"))
	w.line(quote("encoding/json"))
	if secrets {
		w.line()
		w.line(quote(startupPath))
	}
	w.line(")")
	w.line()
	w.line("// ", k.typeName, " is the value of an entry of the kind ", quote(k.name), ", generated")
	w.line("// from its declaration ", quote(k.id), ", version ", quote(k.version), ",")
	w.line("// whose digest is ", quote(k.digest), ".")
	w.declare(k.root, true)
	w.methods(k, secrets)
	w.decoders(k.root)
}

func hasSecret(p *position) bool {
	switch p.shape {
	case shapeSecret:
		return true
	case shapeStruct:
		for _, m := range p.members {
			if hasSecret(m.at) {
				return true
			}
		}
	case shapeArray, shapeMap:
		return hasSecret(p.element)
	}
	return false
}

// declare writes the declarations of p and of every position below it.
func (w *writer) declare(p *position, root bool) {
	switch p.shape {
	case shapeStruct:
		w.structType(p, root)
		for _, m := range p.members {
			w.declare(m.at, false)
		}
	case shapeArray, shapeMap:
		w.declare(p.element, false)
	case shapeEnum:
		w.enumType(p)
	}
}

// goType is the Go type of a value at p, not counting optionality.
func goType(p *position) string {
	switch p.shape {
	case shapeString:
		return "string"
	case shapeInteger:
		return "int64"
	case shapeNumber:
		return "float64"
	case shapeBoolean:
		return "bool"
	case shapeRaw:
		return "json.RawMessage"
	case shapeSecret:
		return "startup.Secret"
	case shapeArray:
		return "[]" + goType(p.element)
	case shapeMap:
		return "map[string]" + goType(p.element)
	}
	return p.typeName
}

// nilWhenAbsent says whether an optional member of p's type is left nil
// when absent, without a pointer: a slice, a map or raw JSON.
func nilWhenAbsent(p *position) bool {
	return p.shape == shapeArray || p.shape == shapeMap || p.shape == shapeRaw
}

// fieldType is the Go type of member m's field: a pointer when it is
// optional, which is nil when the member is absent, except for a slice, a
// map or raw JSON, which is nil itself.
func fieldType(m *member) string {
	if m.required || nilWhenAbsent(m.at) {
		return goType(m.at)
	}
	return "*" + goType(m.at)
}

func describe(m *member) string {
	var b strings.Builder
	if m.at.shape == shapeSecret {
		b.WriteString(", a secret read through the Registry's reader")
	}
	if !m.required {
		b.WriteString(", optional: nil when absent")
	}
	return b.String()
}

func (w *writer) structType(p *position, root bool) {
	if !root {
		w.line()
		w.line("// ", p.typeName, " is the object at ", quote(p.pointer()), ".")
	}
	if len(p.members) == 0 {
		w.line("type ", p.typeName, " struct{}")
		return
	}
	w.line("type ", p.typeName, " struct {")
	for _, m := range p.members {
		w.line("// ", m.field, " is ", quote(m.at.pointer()), describe(m), ".")
		w.line(m.field, " ", fieldType(m))
	}
	w.line("}")
}

func (w *writer) enumType(p *position) {
	w.line()
	w.line("// ", p.typeName, " is a string at ", quote(p.pointer()), ": one of the kind's")
	w.line("// values, which the decoder checks.")
	w.line("type ", p.typeName, " string")
	w.line()
	w.line("// The values of ", p.typeName, ".")
	w.line("const (")
	for _, v := range p.values {
		w.line(p.typeName+part(v), " ", p.typeName, " = ", quote(v))
	}
	w.line(")")
}

// methods writes the kind's two Registry methods.
func (w *writer) methods(k *kind, secrets bool) {
	name := quote(k.name)
	w.line()
	w.line("// ", k.typeName, "IDs returns the ids of the environment's entries of the kind")
	w.line("// ", name, ", in id order.")
	w.line("func (r *Registry) ", k.typeName, "IDs() []string {")
	w.line("return r.ids(", name, ")")
	w.line("}")
	w.line()
	w.line("// ", k.typeName, " decodes the environment's entry of the kind ", name, " with id.")
	if secrets {
		w.line("// It reads each secret the entry refers to through the Registry's reader,")
		w.line("// and returns ErrSecret when one cannot be read.")
	}
	w.line("// It returns ErrNoEntry when there is no such entry, and ErrValue when its")
	w.line("// value does not fit ", k.typeName, ".")
	w.line("func (r *Registry) ", k.typeName, "(ctx context.Context, id string) (*", k.typeName, ", error) {")
	w.line("d, raw, err := r.entry(ctx, ", name, ", id)")
	w.line("if err != nil {")
	w.line("return nil, err")
	w.line("}")
	w.line("v, err := decode", k.typeName, "(d, \"\", raw)")
	w.line("if err != nil {")
	w.line("return nil, err")
	w.line("}")
	w.line("return &v, nil")
	w.line("}")
}

// decoders writes the decoder of each struct and enumeration at or below p.
func (w *writer) decoders(p *position) {
	switch p.shape {
	case shapeStruct:
		w.structDecoder(p)
		for _, m := range p.members {
			w.decoders(m.at)
		}
	case shapeArray, shapeMap:
		w.decoders(p.element)
	case shapeEnum:
		w.enumDecoder(p)
	}
}

// structDecoder writes decode<T>: each member the struct has is read by its
// exact name; a required one that is absent is refused; a member the type
// does not have is ignored (spec RFC 0034 §3.6); no default is applied.
func (w *writer) structDecoder(p *position) {
	zero := p.typeName + "{}"
	w.line()
	w.line("func decode", p.typeName, "(d *decoder, at string, raw json.RawMessage) (", p.typeName, ", error) {")
	if len(p.members) == 0 {
		w.line("if _, err := d.object(at, raw); err != nil {")
		w.line("return ", zero, ", err")
		w.line("}")
		w.line("return ", zero, ", nil")
		w.line("}")
		return
	}
	w.line("members, err := d.object(at, raw)")
	w.line("if err != nil {")
	w.line("return ", zero, ", err")
	w.line("}")
	w.line("var v ", p.typeName)
	for _, m := range p.members {
		name := quote(m.name)
		w.line("if raw0, ok := members[", name, "]; ok {")
		w.line("at0 := member(at, ", name, ")")
		x := w.value(m.at, 0, zero)
		if strings.HasPrefix(fieldType(m), "*") {
			w.line("v.", m.field, " = &", x)
		} else {
			w.line("v.", m.field, " = ", x)
		}
		if m.required {
			w.line("} else {")
			w.line("return ", zero, ", d.missing(member(at, ", name, "))")
		}
		w.line("}")
	}
	w.line("return v, nil")
	w.line("}")
}

func (w *writer) enumDecoder(p *position) {
	names := make([]string, len(p.values))
	for i, v := range p.values {
		names[i] = p.typeName + part(v)
	}
	w.line()
	w.line("func decode", p.typeName, "(d *decoder, at string, raw json.RawMessage) (", p.typeName, ", error) {")
	w.line("s, err := d.readString(at, raw)")
	w.line("if err != nil {")
	w.line("return \"\", err")
	w.line("}")
	w.line("switch v := ", p.typeName, "(s); v {")
	w.line("case ", strings.Join(names, ", "), ":")
	w.line("return v, nil")
	w.line("}")
	w.line("return \"\", d.fail(at, \"is not one of the kind's values\")")
	w.line("}")
}

// value writes the statements that decode the value of position p held by
// the variable raw<depth>, at the pointer held by at<depth>, into the new
// variable x<depth>, which it returns. zero is the enclosing decoder's zero
// result. Arrays and maps are decoded in place, with variables numbered by
// depth.
func (w *writer) value(p *position, depth int, zero string) string {
	d := strconv.Itoa(depth)
	next := strconv.Itoa(depth + 1)
	raw, at, x := "raw"+d, "at"+d, "x"+d
	failed := func() {
		w.line("if err != nil {")
		w.line("return ", zero, ", err")
		w.line("}")
	}
	read := func(call string) {
		w.line(x, ", err := ", call, "(", at, ", ", raw, ")")
		failed()
	}
	switch p.shape {
	case shapeStruct, shapeEnum:
		w.line(x, ", err := decode", p.typeName, "(d, ", at, ", ", raw, ")")
		failed()
	case shapeString:
		read("d.readString")
	case shapeInteger:
		read("d.readInt64")
	case shapeNumber:
		read("d.readFloat64")
	case shapeBoolean:
		read("d.readBool")
	case shapeRaw:
		read("d.readRaw")
	case shapeSecret:
		read("d.readSecret")
	case shapeArray:
		items, i := "items"+d, "i"+d
		w.line(items, ", err := d.array(", at, ", ", raw, ")")
		failed()
		w.line(x, " := make(", goType(p), ", 0, len(", items, "))")
		w.line("for ", i, ", raw", next, " := range ", items, " {")
		w.line("at", next, " := index(", at, ", ", i, ")")
		e := w.value(p.element, depth+1, zero)
		w.line(x, " = append(", x, ", ", e, ")")
		w.line("}")
	case shapeMap:
		members, k := "members"+d, "k"+d
		w.line(members, ", err := d.object(", at, ", ", raw, ")")
		failed()
		w.line(x, " := make(", goType(p), ", len(", members, "))")
		w.line("for _, ", k, " := range sortedNames(", members, ") {")
		w.line("raw", next, " := ", members, "[", k, "]")
		w.line("at", next, " := member(", at, ", ", k, ")")
		e := w.value(p.element, depth+1, zero)
		w.line(x, "[", k, "] = ", e)
		w.line("}")
	}
	return x
}
