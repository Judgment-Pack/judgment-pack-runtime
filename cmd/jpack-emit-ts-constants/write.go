// generate writes the environment's file: for each pinned kind, in name
// order, its type, its entries as an as-const object, and the exported
// constant that aliases the object under a Readonly type of the kind's
// entries. It returns the file, or the diagnostics that refuse it.
func generate(doc *resolved, kinds map[string]*kindDecl, opts options) (file, []diagnostic, error) {
	if isDeviceName(doc.environment) {
		return file{}, []diagnostic{{code: codePath, location: registryLocation(doc.environment)}}, nil
	}
	names, diagnostics, err := checkNames(doc)
	if err != nil || len(diagnostics) > 0 {
		return file{}, diagnostics, err
	}
	types := map[string]*typeNode{}
	for _, p := range doc.pins {
		t, code := kindType(kinds[p.kind])
		if code != "" {
			diagnostics = append(diagnostics, diagnostic{code: code, location: kindLocation(doc, p.kind)})
			continue
		}
		types[p.kind] = t
	}
	if len(diagnostics) > 0 {
		return file{}, diagnostics, nil
	}

	g := &generator{doc: doc, w: &writer{limit: maxFileBytes}}
	for _, p := range doc.pins {
		n := names[p.kind]
		g.w.s("\n// Kind " + p.kind + " " + p.version + ", " + p.digest + ".\nexport type " + n.typeName + " = ")
		g.typ(types[p.kind], "")
		g.w.s(";\n\nconst " + n.entriesName + " = ")
		g.entries(p.kind, kinds[p.kind].secrets)
		g.w.s(" as const;\n\nexport const " + n.constName + ": Readonly<Record<keyof typeof " + n.entriesName + ", " +
			n.typeName + ">> = " + n.entriesName + ";\n")
	}
	if len(g.diagnostics) > 0 {
		return file{}, g.diagnostics, nil
	}
	header := "// Code generated by " + emitterID + " " + emitterVersion + " from registry " + doc.registryDigest + ". DO NOT EDIT.\n"
	if g.usesJSON {
		// An object's members admit undefined, as an absent optional member
		// reads, so that an object type with optional members is a JsonValue.
		header += "\n/** A JSON value: the type of a position whose schema does not narrow it. */\n" +
			"export type JsonValue = null | boolean | number | string | readonly JsonValue[] | { readonly [name: string]: JsonValue | undefined };\n"
	}
	if g.w.over || len(header)+g.w.b.Len() > maxFileBytes {
		return file{}, []diagnostic{{code: codeBounds, location: registryLocation(doc.environment)}}, nil
	}
	return file{path: opts.directory + "/" + doc.environment + ".ts", text: header + g.w.b.String()}, nil, nil
}

// generator writes one file.
type generator struct {
	doc         *resolved
	w           *writer
	usesJSON    bool
	diagnostics []diagnostic
}

func (g *generator) fail(code string, location map[string]any) {
	if len(g.diagnostics) <= maxDiagnostics {
		g.diagnostics = append(g.diagnostics, diagnostic{code: code, location: location})
	}
}

// writer holds the file's text to a byte bound: past it, it stops taking
// text and records that it is over, so a schema written out at every $ref
// never builds more than the bound.
type writer struct {
	b     strings.Builder
	limit int
	over  bool
}

func (w *writer) s(text string) {
	if w.over {
		return
	}
	if w.b.Len()+len(text) > w.limit {
		w.over = true
		return
	}
	w.b.WriteString(text)
}

// typ writes a type. indent is the indentation of the line it starts on.
// A type node can be shared, as a member's type is in the index signature's
// union, so the walk of a $ref chain can grow exponentially. Once the writer
// is over its bound the walk stops, and each call that does not stop writes
// a byte or has two parts, so the walk is bounded by the file's bound.
func (g *generator) typ(t *typeNode, indent string) {
	if g.w.over {
		return
	}
	switch t.op {
	case opKeyword:
		g.usesJSON = g.usesJSON || t == typeJSON
		g.w.s(t.keyword)
	case opLiteral:
		g.literalType(t.value)
	case opArray:
		g.w.s("readonly ")
		elem := t.elem
		_, tuple := elem.value.([]any)
		parens := elem.op == opUnion || elem.op == opIntersection || elem.op == opArray || elem.op == opLiteral && tuple
		if parens {
			g.w.s("(")
		}
		g.typ(elem, indent)
		if parens {
			g.w.s(")")
		}
		g.w.s("[]")
	case opObject:
		if len(t.members) == 0 && t.index == nil {
			g.w.s("{ readonly [name: string]: never }")
			return
		}
		inner := indent + "  "
		g.w.s("{\n")
		for _, m := range t.members {
			g.w.s(inner + "readonly " + jsString(m.name))
			if m.optional {
				g.w.s("?")
			}
			g.w.s(": ")
			g.typ(m.t, inner)
			g.w.s(";\n")
		}
		if t.index != nil {
			g.w.s(inner + "readonly [name: string]: ")
			g.typ(t.index, inner)
			g.w.s(";\n")
		}
		g.w.s(indent + "}")
	case opUnion:
		for i, part := range t.parts {
			if i > 0 {
				g.w.s(" | ")
			}
			g.typ(part, indent)
		}
	case opIntersection:
		for i, part := range t.parts {
			if i > 0 {
				g.w.s(" & ")
			}
			if part.op == opUnion {
				g.w.s("(")
				g.typ(part, indent)
				g.w.s(")")
				continue
			}
			g.typ(part, indent)
		}
	}
}

// literalType writes a JSON value as its literal type, on one line.
func (g *generator) literalType(value any) {
	if g.w.over {
		return
	}
	switch v := value.(type) {
	case map[string]any:
		if len(v) == 0 {
			g.w.s("{ readonly [name: string]: never }")
			return
		}
		g.w.s("{ ")
		for i, name := range sortedNames(v) {
			if i > 0 {
				g.w.s("; ")
			}
			g.w.s("readonly " + jsString(name) + ": ")
			g.literalType(v[name])
		}
		g.w.s(" }")
	case []any:
		g.w.s("readonly [")
		for i, item := range v {
			if i > 0 {
				g.w.s(", ")
			}
			g.literalType(item)
		}
		g.w.s("]")
	default:
		g.w.s(scalar(v))
	}
}

// scalar writes a JSON scalar: null, true, false, a number as its JSON
// literal, which is a JavaScript one, and a string as jsString writes it.
func scalar(value any) string {
	switch v := value.(type) {
	case nil:
		return "null"
	case bool:
		if v {
			return "true"
		}
		return "false"
	case json.Number:
		return v.String()
	case string:
		return jsString(v)
	}
	// The decoder gives no other scalar.
	panic("jpack-emit-ts-constants: a value of no JSON type")
}

// entries writes a kind's entries as an object literal, by entry id, each
// entry's value with its secret positions left out. An entry id __proto__ is
// refused.
func (g *generator) entries(kind string, secrets patterns) {
	var ids []entry
	for _, e := range g.doc.entries {
		if e.kind == kind {
			ids = append(ids, e)
		}
	}
	if len(ids) == 0 {
		g.w.s("{}")
		return
	}
	g.w.s("{\n")
	for _, e := range ids {
		if e.id == "__proto__" {
			g.fail(codeMemberProto, valueLocation(g.doc.environment, e, nil))
			continue
		}
		g.w.s("  " + jsString(e.id) + ": ")
		g.value(e.value, secrets, "  ", e, nil)
		g.w.s(",\n")
	}
	g.w.s("}")
}

// value writes an entry's value at path, with every member at which a
// pattern of ps ends left out. A pattern that ends at an array item, which
// the schema should have refused, is refused here too, and so is a member
// named __proto__ that would be written.
func (g *generator) value(v any, ps patterns, indent string, e entry, path []string) {
	switch typed := v.(type) {
	case map[string]any:
		type kept struct {
			name  string
			below patterns
		}
		var members []kept
		for _, name := range sortedNames(typed) {
			below := ps.member(name)
			if below.ends() {
				continue
			}
			if name == "__proto__" {
				g.fail(codeMemberProto, valueLocation(g.doc.environment, e, appendPath(path, name)))
				continue
			}
			members = append(members, kept{name, below})
		}
		if len(members) == 0 {
			g.w.s("{}")
			return
		}
		inner := indent + "  "
		g.w.s("{\n")
		for _, m := range members {
			g.w.s(inner + jsString(m.name) + ": ")
			g.value(typed[m.name], m.below, inner, e, appendPath(path, m.name))
			g.w.s(",\n")
		}
		g.w.s(indent + "}")
	case []any:
		flat := true
		below := make([]patterns, len(typed))
		for i, item := range typed {
			index := strconv.Itoa(i)
			if below[i] = ps.member(index); below[i].ends() {
				g.fail(codeSecretInArray, valueLocation(g.doc.environment, e, appendPath(path, index)))
			}
			switch item.(type) {
			case map[string]any, []any:
				flat = false
			}
		}
		if len(typed) == 0 || flat {
			g.w.s("[")
			for i, item := range typed {
				if i > 0 {
					g.w.s(", ")
				}
				g.value(item, below[i], indent, e, appendPath(path, strconv.Itoa(i)))
			}
			g.w.s("]")
			return
		}
		inner := indent + "  "
		g.w.s("[\n")
		for i, item := range typed {
			g.w.s(inner)
			g.value(item, below[i], inner, e, appendPath(path, strconv.Itoa(i)))
			g.w.s(",\n")
		}
		g.w.s(indent + "]")
	default:
		g.w.s(scalar(typed))
	}
}

// appendPath returns path and one more token, never sharing path's array.
func appendPath(path []string, token string) []string {
	return append(path[:len(path):len(path)], token)
}

// jsString writes s as a double-quoted JavaScript string literal of ASCII
// only: a quotation mark and a reverse solidus escaped, the short escapes for
// backspace, tab, line feed, form feed and carriage return, \u00XX for every
// other control character and DEL, \u003c for <, and every code point outside
// ASCII as the \uXXXX escapes of its UTF-16 code units. So a line
// terminator, U+2028 and U+2029 among them, never stands in the source, no
// text can end the literal, and a module inlined into an HTML script element
// holds no </script or <!-- to end it. The decoder admits only valid UTF-8
// with no lone surrogate.
func jsString(s string) string {
	const hex = "0123456789abcdef"
	b := make([]byte, 0, len(s)+2)
	b = append(b, '"')
	unit := func(u uint16) {
		b = append(b, '\\', 'u', hex[u>>12], hex[u>>8&0xf], hex[u>>4&0xf], hex[u&0xf])
	}
	for _, r := range s {
		switch {
		case r == '"' || r == '\\':
			b = append(b, '\\', byte(r))
		case r == '\b':
			b = append(b, '\\', 'b')
		case r == '\t':
			b = append(b, '\\', 't')
		case r == '\n':
			b = append(b, '\\', 'n')
		case r == '\f':
			b = append(b, '\\', 'f')
		case r == '\r':
			b = append(b, '\\', 'r')
		case r < 0x20 || r == 0x7f || r == '<':
			unit(uint16(r))
		case r < 0x80:
			b = append(b, byte(r))
		default:
			for _, u := range utf16.Encode([]rune{r}) {
				unit(u)
			}
		}
	}
	return string(append(b, '"'))
}

// sortedNames returns the names of m in RFC 8785 order, by their UTF-16 code
// units, so that the order never depends on the map's.
func sortedNames[V any](m map[string]V) []string {
	names := make([]string, 0, len(m))
	for name := range m {
		names = append(names, name)
	}
	slices.SortFunc(names, compareUTF16)
	return names
}

// compareUTF16 orders two strings by their UTF-16 code units, then by their
// bytes.
func compareUTF16(x, y string) int {
	if c := slices.Compare(utf16.Encode([]rune(x)), utf16.Encode([]rune(y))); c != 0 {
		return c
	}
	return strings.Compare(x, y)
}

// isDeviceName says whether Windows reads a file name as a device: its name
// before the first ".", without trailing spaces, is CON, PRN, AUX, NUL, or
// COM or LPT and a digit from 1 to 9, in any case. The host refuses such a
// path; an environment of one of these names is refused here with a
// diagnostic first.
func isDeviceName(name string) bool {
	base, _, _ := strings.Cut(name, ".")
	base = strings.TrimRight(base, " ")
	switch len(base) {
	case 3:
		for _, device := range []string{"CON", "PRN", "AUX", "NUL"} {
			if strings.EqualFold(base, device) {
				return true
			}
		}
	case 4:
		prefix := base[:3]
		return (strings.EqualFold(prefix, "COM") || strings.EqualFold(prefix, "LPT")) && base[3] >= '1' && base[3] <= '9'
	}
	return false
}
